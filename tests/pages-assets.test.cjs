const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { prepare } = require('../scripts/prepare-pages.cjs');
test('a changed stylesheet or script receives a new URL while unchanged assets keep theirs', t => {
 const root = fs.mkdtempSync(path.join(os.tmpdir(), 'nightwatch-pages-'));
 t.after(() => fs.rmSync(root, { recursive: true, force: true }));
 fs.mkdirSync(path.join(root, 'dist/vendor/leaflet'), { recursive: true });
 fs.writeFileSync(path.join(root, 'dist/index.html'), '<link rel="stylesheet" href="style.css"><link rel="stylesheet" href="vendor/leaflet/leaflet.css"><script src="app.js"></script>');
 fs.writeFileSync(path.join(root, 'dist/style.css'), 'body{color:white}');
 fs.writeFileSync(path.join(root, 'dist/vendor/leaflet/leaflet.css'), '.icon{background:url(images/marker.png)}');
 fs.writeFileSync(path.join(root, 'dist/app.js'), 'console.log("first")');
 const first = prepare(root), firstScript = first.manifest['app.js'];
 const leaflet = first.manifest['vendor/leaflet/leaflet.css'];
 assert.equal(path.dirname(leaflet), 'vendor/leaflet');
 fs.writeFileSync(path.join(root, 'dist/style.css'), 'body{color:green}');
 fs.writeFileSync(path.join(root, 'dist/app.js'), 'console.log("map update")');
 const next = prepare(root);
 assert.notEqual(next.manifest['app.js'], firstScript);
 assert.notEqual(next.manifest['style.css'], first.manifest['style.css']);
 assert.equal(next.manifest['vendor/leaflet/leaflet.css'], leaflet);
 const html = fs.readFileSync(path.join(next.output, 'index.html'), 'utf8');
 assert(html.includes(next.manifest['app.js']));
 assert(!html.includes('src="app.js"'));
 for (const [original, versioned] of Object.entries(next.manifest)) assert(fs.readFileSync(path.join(next.output, versioned)).equals(fs.readFileSync(path.join(root, 'dist', original))));
 assert(fs.existsSync(path.join(next.output, 'app.js')), 'Retain canonical URLs for older pages');
});
test('current Nightwatch map, app, CSS, and Leaflet are all versioned together', t => {
 const root = path.resolve(__dirname, '..');
 const output = fs.mkdtempSync(path.join(os.tmpdir(), 'nightwatch-release-'));
 t.after(() => fs.rmSync(output, { recursive: true, force: true }));
 const { manifest } = prepare(root, output);
 for (const file of ['app.js', 'style.css', 'cloud-map.js', 'aurora-map.js', 'weather-utils.js', 'vendor/leaflet/leaflet.css', 'vendor/leaflet/leaflet.js']) assert(manifest[file], file);
 const html = fs.readFileSync(path.join(output, 'index.html'), 'utf8');
 const scripts = Array.from(html.matchAll(/<script src="([^"]+)"/g), m => m[1]);
 assert(scripts.indexOf(manifest['vendor/leaflet/leaflet.js']) < scripts.indexOf(manifest['cloud-map.js']));
 assert(scripts.indexOf(manifest['weather-utils.js']) < scripts.indexOf(manifest['cloud-map.js']));
 assert(scripts.indexOf(manifest['aurora-map.js']) < scripts.indexOf(manifest['cloud-map.js']));
 assert(scripts.indexOf(manifest['cloud-map.js']) < scripts.indexOf(manifest['app.js']));
});
